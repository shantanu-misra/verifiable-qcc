"""Generate the self-contained Kaggle kernel script `train_kaggle.py` from the task modules.

The kernel runs `train_mps.py`'s trainer on CUDA with the competition data attached at
/kaggle/input/google-verifiable-quantum-circuit-compilation (the verifier's metric modules are loaded from there by
dfthc_tools), checkpoints every stage to /kaggle/working/stage_R<R>.npz and is seeded.  Modules are concatenated
in dependency order with their internal imports replaced by aliases to this one module.

    python3 tasks/dfthcsos/kaggle/build_kernel.py            # writes tasks/dfthcsos/kaggle/train_kaggle.py
    python3 -m kaggle kernels push -p tasks/dfthcsos/kaggle  # (kernel-metadata.json alongside)
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.dirname(HERE)
ORDER = ["dfthc_tools.py", "refit.py", "thc_fit.py", "prune.py", "train_mps.py"]
HEADER = '''# GENERATED by tasks/dfthcsos/kaggle/build_kernel.py from dfthc_tools.py, refit.py, thc_fit.py, prune.py,
# train_mps.py -- do not edit; edit the sources and rebuild.  Kaggle GPU kernel for the dfthcsos factorisation training.
from __future__ import annotations
import os, sys
ON_KAGGLE = os.path.isdir("/kaggle/input")
if ON_KAGGLE:
    # The competition data's layout on Kaggle may differ from the local unzip: locate the files.
    def _find(target, root="/kaggle/input", want_dir=False, max_depth=6):
        root_depth = root.rstrip("/").count("/")
        for dp, dn, fn in os.walk(root):
            if dp.count("/") - root_depth > max_depth:
                dn[:] = []
                continue
            if (want_dir and target in dn) or (not want_dir and target in fn):
                return os.path.join(dp, target)
        return None
    for top in sorted(os.listdir("/kaggle/input")):
        p = os.path.join("/kaggle/input", top)
        print("input:", p, sorted(os.listdir(p))[:12] if os.path.isdir(p) else "")
    # the verifier package (scoreinfra/dfthc_math.py + the FCIDUMP next to it) lives in the competition data;
    # the starter-kit dataset also ships the FCIDUMP, so key on the package, not the file
    dm_path = _find("dfthc_math.py")
    sample = _find("angle_k_0.kmb") or _find("angle_k_0.kmx")
    print("found dfthc_math:", dm_path, " sample:", sample)
    if dm_path is None or sample is None:
        raise SystemExit("competition data not found under /kaggle/input")
    verifier_dir = os.path.dirname(os.path.dirname(dm_path))
    if not os.path.exists(os.path.join(verifier_dir, "FeMoCo76o113e.fcidump")):
        raise SystemExit(f"no FCIDUMP in {verifier_dir}")
    os.environ["VQCC_VERIFIER_DIR"] = verifier_dir
    os.environ["VQCC_SAMPLE_DIR"] = os.path.dirname(sample)
    os.environ.setdefault("VQCC_DATA", "/kaggle/input/google-verifiable-quantum-circuit-compilation")
    os.environ.setdefault("VQCC_BUILD", "/tmp/vqcc_build")
    os.makedirs("/tmp/vqcc_build", exist_ok=True)
dt = rf = tf = pr = sys.modules[__name__]
'''
FOOTER = '''

if __name__ == "__main__":
    if ON_KAGGLE and len(sys.argv) == 1:
        # Kaggle chain: the public schedule from the baseline, seed 1 (the Mac runs 60,55,48,... with seed 0).
        # A P100/V100/A100 has fast float64: run L-BFGS in float64 (20k evaluations per stage); a T4 does not:
        # float32 Adam, 100k steps per stage.
        import torch as _t
        name = _t.cuda.get_device_name(0) if _t.cuda.is_available() else "cpu"
        fast64 = any(k in name for k in ("P100", "V100", "A100", "H100"))
        print("GPU:", name, "-> float64 L-BFGS" if fast64 else "-> float32 Adam")
        opt_args = (["--dtype", "float64", "--optim", "lbfgs", "--steps", os.environ.get("VQCC_STEPS", "20000"), "--eval-every", "200"]
                    if fast64 else ["--dtype", "float32", "--optim", "adam", "--steps", os.environ.get("VQCC_STEPS", "100000"),
                                    "--eval-every", "2000", "--lr", "3e-4", "--lr-end", "3e-6"])
        sys.argv += ["--device", "cuda" if _t.cuda.is_available() else "cpu", "--out-prefix", "/kaggle/working/stage_",
                     "--init", os.environ.get("VQCC_INIT", "baseline"),
                     "--schedule", os.environ.get("VQCC_SCHEDULE", "55,48,42,36,32,28,26"), "--seed", "1"] + opt_args
    main()
'''


def strip(src: str, name: str = "") -> str:
    if name == "dfthc_tools.py":
        # its `rf` is the verifier's reference module; in the other modules `rf` means refit
        src = re.sub(r"\brf\b", "rfmod", src)
    out = []
    skip_main = False
    for line in src.splitlines():
        if line.startswith("from __future__ import annotations"):
            continue
        if re.match(r"^import (dfthc_tools|refit|thc_fit|prune) as \w+", line):
            continue
        if line.startswith('if __name__ == "__main__":'):
            skip_main = True
            continue
        if skip_main:
            if line.startswith(" ") or not line.strip():
                continue
            skip_main = False
        out.append(line)
    return "\n".join(out)


def main() -> None:
    parts = [HEADER]
    for name in ORDER:
        with open(os.path.join(SRC, name), encoding="utf-8") as f:
            parts.append(f"\n\n# ======================================================================\n# {name}\n# ======================================================================\n")
            parts.append(strip(f.read(), name))
    parts.append(FOOTER)
    out = os.path.join(HERE, "train_kaggle.py")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))
    print(f"wrote {out} ({sum(len(p) for p in parts)//1024} KB)")


if __name__ == "__main__":
    main()
