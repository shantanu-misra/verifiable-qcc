#!/usr/bin/env python3
"""Negative tests for the official invsqrt verifier.

Builds deliberately broken variants of the baseline circuit, runs the official verifier on each,
and writes results/verifier_checks.md recording that every variant is rejected (and the unmodified
control passes). Also recomputes the baseline scores from runs/*_baseline_full.json to confirm the
cost formulas. Run inside the Docker image:

    docker compose run --rm -T dev python scripts/verifier_checks.py

All runs use --max-x 4096 (262,144 shots): rejections surface on the first batch, and the
control's PASS is a smoke test, not a reportable score (runs/invsqrt_baseline_full.json is).
"""
from __future__ import annotations

import datetime
import hashlib
import io
import json
import math
import os
import re
import subprocess
import sys
import tempfile

import kickmix as km

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASELINE = os.path.join(ROOT, 'data/sample_submission/invsqrt.kmb')
VERIFIER = os.path.join(ROOT, 'data/verifiers/invsqrt/verify_submission_invsqrt.py')
INVSQRT_JSON = os.path.join(ROOT, 'runs/invsqrt_baseline_full.json')
DQI_JSON = os.path.join(ROOT, 'runs/dqi_baseline_full.json')
OUT = os.path.join(ROOT, 'results/verifier_checks.md')
MAX_X = 4096


def sha256_kmb(c: km.Circuit) -> str:
    buf = io.BytesIO()
    c.to_file(buf, format='kmb')
    return hashlib.sha256(buf.getvalue()).hexdigest()


def kmx_text(c: km.Circuit) -> str:
    buf = io.BytesIO()
    c.to_file(buf, format='kmx')
    return buf.getvalue().decode('utf-8')


def qubit_index(target, num_qubits: int) -> int:
    return next(i for i in range(num_qubits) if km.q(i) == target)


def run_verifier(path: str) -> tuple[int, dict]:
    p = subprocess.run([sys.executable, VERIFIER, path, '--max-x', str(MAX_X)],
                       capture_output=True, text=True)
    try:
        return p.returncode, json.loads(p.stdout)
    except json.JSONDecodeError:
        return p.returncode, {'status': 'NO-JSON', 'error': (p.stdout + p.stderr)[-500:]}


def main() -> int:
    base = km.Circuit.from_file(BASELINE)
    base_sha = sha256_kmb(base)
    text = kmx_text(base)
    roundtrip_ok = sha256_kmb(km.Circuit(text)) == base_sha

    x_reg = list(base.register_data['x'])
    x0 = qubit_index(x_reg[0], base.num_qubits)
    x_set = set(x_reg)
    scratch0 = next(i for i in range(base.num_qubits) if km.q(i) not in x_set)
    renamed = re.sub(r'^(REGISTER r\d+) "x"', r'\1 "y"', text, count=1, flags=re.M)
    assert renamed != text, 'could not find the REGISTER line for "x"'

    variants = [
        ('control', 'unmodified baseline', text, 'PASS'),
        ('dirty_scratch', f'append `X q{scratch0}`: a scratch qubit ends in |1>', text + f'X q{scratch0}\n', 'FAIL'),
        ('x_not_restored', f'append `X q{x0}`: the x register is corrupted', text + f'X q{x0}\n', 'FAIL'),
        ('wrong_phase', f'append `Z q{x0}`: extra half-turn phase whenever x is odd', text + f'Z q{x0}\n', 'FAIL'),
        ('bad_register', 'rename register "x" to "y": schema violation', renamed, 'FAIL'),
    ]

    rows = []
    all_ok = True
    with tempfile.TemporaryDirectory() as tmp:
        for name, change, body, expected in variants:
            path = os.path.join(tmp, f'{name}.kmx')
            with open(path, 'w', encoding='utf-8') as f:
                f.write(body)
            rc, out = run_verifier(path)
            status = out.get('status')
            ok = status == expected and (rc == 0) == (expected == 'PASS')
            all_ok &= ok
            detail = (f'score={out["score"]:.2f}, worst err/tol={out["worst_error_over_tolerance"]:.3f}'
                      if status == 'PASS' else out.get('error', '')[:160])
            rows.append((name, change, expected, status, rc, 'yes' if ok else 'NO', detail))
            print(f'{name:16} expected={expected:4} got={status:4} rc={rc} ok={ok}  {detail}')

    inv = json.load(open(INVSQRT_JSON))
    q, c = inv['num_qubits'], inv['toffoli_equivalent']
    c_parts = inv['toffoli_count'] + (inv['t_count'] + inv['rotation_count'] * (
        0.56 * math.log2(1 / inv['rotation_eps']) + 5.3)) / 4
    dqi = json.load(open(DQI_JSON))
    r, qd, td, eps = (dqi['repetition_factor'], dqi['num_qubits'], dqi['toffoli_count'],
                      dqi['effective_error_rate'])
    r_formula = math.log(2) / -math.log(0.5 + 2 * math.sqrt(eps))

    lines = [
        '# Official invsqrt verifier: negative checks',
        '',
        f'Generated by `scripts/verifier_checks.py` on {datetime.datetime.now(datetime.timezone.utc):%Y-%m-%d %H:%MZ} '
        f'inside the Docker image (kickmix {getattr(km, "__version__", "?")}), '
        f'baseline `data/sample_submission/invsqrt.kmb` sha256 `{base_sha[:16]}…`, every run with `--max-x {MAX_X}`.',
        '',
        f'- kmx round trip preserves the circuit (same canonical .kmb sha256): **{"yes" if roundtrip_ok else "NO"}**',
        f'- x register qubit used: q{x0}; scratch qubit used: q{scratch0}; Q = `num_qubits` = {base.num_qubits}',
        '',
        '| variant | modification | expected | verifier status | exit | as expected | message / smoke score |',
        '|---|---|---|---|---|---|---|',
    ]
    for name, change, expected, status, rc, ok, detail in rows:
        cells = [name, change, expected, status, str(rc), ok, detail]
        lines.append('| ' + ' | '.join(c.replace('|', '\\|') for c in cells) + ' |')
    lines += [
        '',
        f'The control score above is a `--max-x {MAX_X}` smoke test and is **not** reportable; the official',
        'full-run score is in `runs/invsqrt_baseline_full.json`.',
        '',
        '## Cost formulas recomputed from the full-run JSON',
        '',
        f'- invsqrt: Q × C = {q} × {c!r} = {q * c!r}; reported `score` = {inv["score"]!r} → '
        f'**{"equal" if q * c == inv["score"] else "DIFFERENT"}**',
        f'- invsqrt: C from parts = toffoli_count + (t_count + rotation_count·(0.56·log2(1/rotation_eps) + 5.3))/4 '
        f'= {c_parts!r} → **{"equal" if c_parts == c else "DIFFERENT"}**',
        f'- dqi: R × Q² × T = {r!r} × {qd}² × {td!r} = {r * qd * qd * td!r}; reported `score` = {dqi["score"]!r} → '
        f'**{"equal" if r * qd * qd * td == dqi["score"] else "DIFFERENT"}**',
        f'- dqi: R(ε⁺) = ln2 / −ln(1/2 + 2√ε⁺) with ε⁺ = {eps!r} → {r_formula!r} → '
        f'**{"equal" if r_formula == r else "DIFFERENT"}**',
        '',
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print(f'wrote {os.path.relpath(OUT, ROOT)}; all checks as expected: {all_ok and roundtrip_ok}')
    return 0 if all_ok and roundtrip_ok else 1


if __name__ == '__main__':
    sys.exit(main())
